function call(path,{id=admin,origin,body,cookie,type="application/json",secret=pepper,store=bucket,fetchSite,method}={}) {
  const headers=new Headers();
  if (id) headers.set("oai-authenticated-user-id",id);
  if (origin) headers.set("origin",origin);
  if (cookie) headers.set("cookie",cookie);
  if (fetchSite) headers.set("sec-fetch-site",fetchSite);
  if (body!==undefined) headers.set("content-type",type);
  return app.fetch(new Request(host+path,{headers,method:method || (body===undefined?"GET":"POST"),body:body===undefined?undefined:JSON.stringify(body)}),{BUCKET:store,PP_PASSWORD_PEPPER:secret});
}
