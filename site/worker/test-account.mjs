const makeBucket=()=>{
  const records=new Map();
  let version=0;
  return {records,
    async get(key) {
      const x=records.get(key);
      return x ? {etag:x.etag,json:async()=>JSON.parse(x.body)} : null;
    },
    async put(key, body, options={}) {
      const x=records.get(key), onlyIf=options.onlyIf||{};
      if((onlyIf.etagDoesNotMatch==="*" && x) || (onlyIf.etagMatches && onlyIf.etagMatches!==x?.etag)) return null;
      const next={etag:String(++version),body};
      records.set(key,next);
      return next;
    }
  };
};
